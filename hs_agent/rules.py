"""归类总规则（GRI）和类注、章注。

总规则是归类推理的法律依据，直接写进系统提示词。下面是六条规则的要点概括，正式文本以《进出口税则》为准。
类注、章注篇幅大且有版权问题，项目不附带；把文本放进 data/notes/ 即可被 Agent 查阅（见 README）。
"""

from __future__ import annotations

from pathlib import Path

GRI = """归类总规则（要点）：
规则一：类、章及分章的标题仅为查找方便而设；具有法律效力的归类，应按品目条文和有关类注、章注确定。
规则二：(一) 品目所列货品包括已具有完整品或制成品基本特征的不完整品、未制成品，以及未组装或拆散的完整品。
        (二) 品目所列材料包括该材料与其他材料的混合物或组合物；由一种以上材料构成的货品按规则三归类。
规则三：货品看起来可归入两个及以上品目时：
        (一) 列名比较具体的品目优先于列名一般的品目；但若各品目都只述及混合物或组合货品中的部分材料，或零售成套货品中的部分货品，视为同样具体。
        (二) 混合物、不同材料构成或不同部件组成的组合货品、零售成套货品，按构成其基本特征的材料或部件归类。
        (三) 按上面两条仍无法确定的，归入可考虑品目中顺序号最大的品目。
规则四：按以上规则无法归类的，归入与其最相类似的货品的品目。
规则五：(一) 专门盛装某物品、适合长期使用的箱、盒、套等，与所装物品一同进出口并通常一同出售的，与物品一并归类；本身构成整个货品基本特征的除外。
        (二) 包装材料和包装容器与所装货品一并归类，明显可重复使用的除外。
规则六：子目的归类按子目条文、子目注释以及以上规则确定，只有同一级别的子目才能比较；除另有规定外，类注、章注也适用于子目。
"""


def load_notes(notes_dir: Path, section: str, chapter: str) -> str:
    """返回某类、某章的注释原文（如果用户放了文件），文件名：section_XVI.md、chapter_85.md。"""
    parts = []
    for name in (f"section_{section}.md", f"chapter_{chapter}.md"):
        p = notes_dir / name
        if p.exists():
            parts.append(f"【{name[:-3]}】\n" + p.read_text(encoding="utf-8").strip())
    return "\n\n".join(parts)
